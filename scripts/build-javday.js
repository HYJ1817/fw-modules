#!/usr/bin/env node
/**
 * JAVDay：上游是 Forward/Rex 原生模块（自带 WidgetMetadata），但元信息缺 id/type/icon、
 * 栏目地址靠 type:"constant" 参数传，换个宿主就失效。
 * 这里保留上游全部函数，只换掉元信息、给每个栏目配一个固定入口函数。
 *
 *   lib/vendor/javday-core.js  上游原文（含它自己的 WidgetMetadata，构建时剥掉）
 *   lib/entries/javday.js      新元信息 + 栏目入口函数
 *     → widgets/javday.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BANNER = "/* Generated by scripts/build-javday.js. Metadata in lib/entries/, upstream logic in lib/vendor/. Do not edit directly. */";

const entry = fs.readFileSync(path.join(ROOT, "lib/entries/javday.js"), "utf8").replace(/\r\n/g, "\n");
let core = fs.readFileSync(path.join(ROOT, "lib/vendor/javday-core.js"), "utf8").replace(/\r\n/g, "\n");

// 剥掉上游自带的 WidgetMetadata 块（从声明到与之配对的 "};"）
const start = core.indexOf("var WidgetMetadata");
if (start < 0) { console.error("上游文件里找不到 WidgetMetadata"); process.exit(1); }
let depth = 0, end = -1;
for (let i = core.indexOf("{", start); i < core.length; i++) {
  const ch = core[i];
  if (ch === "{") depth++;
  else if (ch === "}") { depth--; if (depth === 0) { end = i + 1; break; } }
}
if (end < 0) { console.error("WidgetMetadata 括号不配对"); process.exit(1); }
core = core.slice(0, start) + "/* 上游的 WidgetMetadata 已由 lib/entries/javday.js 替换 */\n" + core.slice(end).replace(/^;/, "");

// 上游搜索用的是 /search/?wd=关键词，站点现在对查询串形式回 403；改成路径形式
const before = core;
core = core.replace(
  'searchUrl = `https://javday.app/search/?wd=${keyword}`;',
  'searchUrl = `https://javday.app/search/${encodeURIComponent(keyword)}/`;'
);
core = core.replace(
  'searchUrl = `https://javday.app/search/page/${page}/wd/${keyword}/`;',
  'searchUrl = `https://javday.app/search/page/${page}/wd/${encodeURIComponent(keyword)}/`;'
);
if (core === before) console.warn("⚠ 未匹配到搜索地址模板，请检查上游是否改过");

if (!/WidgetMetadata\s*=/.test(entry)) { console.error("入口层缺少 WidgetMetadata"); process.exit(1); }

const output = `${BANNER}\n\n${entry.trimEnd()}\n\n/* ==================== 上游实现（函数体逐字保留） ==================== */\n\n${core.trimEnd()}\n`;
fs.writeFileSync(path.join(ROOT, "widgets/javday.js"), output);
console.log(`✓ widgets/javday.js  ${(output.length / 1024).toFixed(1)}KB / ${output.split("\n").length} 行`);
