#!/usr/bin/env node
/**
 * 黑桃短剧（WeBox 移植版）：桥接层 + 上游原文 → widgets/heitao.js
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const BANNER = "/* Generated by scripts/build-heitao.js. Bridge in lib/entries/, upstream core in lib/vendor/. Do not edit directly. */";
const entry = fs.readFileSync(path.join(ROOT, "lib/entries/heitao.js"), "utf8").replace(/\r\n/g, "\n");
const core = fs.readFileSync(path.join(ROOT, "lib/vendor/heitao-core.js"), "utf8").replace(/\r\n/g, "\n");
if (!/WidgetMetadata\s*=/.test(entry)) { console.error("入口层缺少 WidgetMetadata"); process.exit(1); }
if (!/WeBox\.define\(/.test(core)) { console.error("lib/vendor/heitao-core.js 不是 WeBox 插件原文"); process.exit(1); }
const output = `${BANNER}\n\n${entry.trimEnd()}\n\n/* ==================== 上游 WeBox 插件原文（勿改） ==================== */\n\n${core.trimEnd()}\n`;
fs.writeFileSync(path.join(ROOT, "widgets/heitao.js"), output);
console.log(`✓ widgets/heitao.js  ${(output.length / 1024).toFixed(1)}KB / ${output.split("\n").length} 行`);
