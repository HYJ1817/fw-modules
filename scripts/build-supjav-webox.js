#!/usr/bin/env node
/**
 * SupJav（WeBox 移植版）：把上游 WeBox 插件原文接在桥接层之后，生成自包含 widget。
 *
 *   lib/entries/supjav-webox.js  （桥接层：WidgetMetadata + ctx 兼容 + 结果映射）
 *   lib/vendor/supjav-webox-core.js（上游原文，逐字保留，勿改）
 *     → widgets/supjav-webox.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BANNER = "/* Generated by scripts/build-supjav-webox.js. Bridge in lib/entries/, upstream core in lib/vendor/. Do not edit directly. */";

const entry = fs.readFileSync(path.join(ROOT, "lib/entries/supjav-webox.js"), "utf8").replace(/\r\n/g, "\n");
const core = fs.readFileSync(path.join(ROOT, "lib/vendor/supjav-webox-core.js"), "utf8").replace(/\r\n/g, "\n");

if (!/WidgetMetadata\s*=/.test(entry)) {
  console.error("lib/entries/supjav-webox.js 缺少 WidgetMetadata");
  process.exit(1);
}
if (!/WeBox\.define\(/.test(core)) {
  console.error("lib/vendor/supjav-webox-core.js 不是 WeBox 插件原文");
  process.exit(1);
}

// 上游原文顶部的 const 声明与本文件的 var 不冲突，直接拼接即可
const output = `${BANNER}\n\n${entry.trimEnd()}\n\n/* ==================== 上游 WeBox 插件原文（勿改） ==================== */\n\n${core.trimEnd()}\n`;
const target = path.join(ROOT, "widgets/supjav-webox.js");
fs.writeFileSync(target, output);
console.log(`✓ widgets/supjav-webox.js  ${(output.length / 1024).toFixed(1)}KB / ${output.split("\n").length} 行`);
