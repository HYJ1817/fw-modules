const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const original = fs.readFileSync(path.join(root, 'widgets/fw-all.js'), 'utf8');
const match = original.match(/var WidgetMetadata = (\{[\s\S]*?\n\});/);
if (!match) throw Error('Missing bundle metadata');
const metadata = JSON.parse(match[1]);
metadata.id = 'hyj1817.fw.trace';
metadata.title = 'FW 总模块·诊断副本';
metadata.version = '1.0.0';
metadata.description = '独立副本：从此模块首页复现，再测试“诊断：读取记录”。不替换原版。';
metadata.detailCacheDuration = 0;
const entries = [...new Set(metadata.modules.map(m => m.functionName).concat(metadata.search.functionName, 'loadDetail'))];
metadata.modules.forEach(m => { m.title = '[诊断] ' + m.title; m.cacheDuration = 0; });
metadata.modules.unshift(
  { id: 'traceStart', title: '诊断：开始新记录', functionName: 'startTrace', requiresWebView: false, cacheDuration: 0, params: [] },
  { id: 'traceRead', title: '诊断：读取记录', functionName: 'readTrace', requiresWebView: false, cacheDuration: 0, params: [] }
);
const runtime = fs.readFileSync(path.join(root, 'scripts/fw-trace-runtime.js'), 'utf8');
let count = 0;
let output = original.replace(match[0], 'var WidgetMetadata = ' + JSON.stringify(metadata, null, 2) + ';\n\n' + runtime)
  .replace(/var (FW_[A-Z0-9_]+) = \(function \(\) \{\nvar WidgetMetadata;/g, (_, namespace) => {
    count++;
    return 'var ' + namespace + ' = (function () {\nvar Widget = fwtHost(' + JSON.stringify(namespace) + ');\nvar console = fwtConsole(' + JSON.stringify(namespace) + ');\nvar WidgetMetadata;';
  });
if (count !== 7) throw Error('Expected seven isolated provider namespaces; got ' + count);
output += '\n' + entries.map(name => name + ' = fwtWrap(' + JSON.stringify(name) + ', ' + name + ');').join('\n') + '\n';
output = output.replace('/* Generated by scripts/build-fw-all.js. Do not edit directly. */', '/* Generated by scripts/build-fw-trace.js. Independent diagnostic copy; do not edit directly. */');
const check = { console: { log() {} }, Widget: { http: {}, storage: null, sharedCache: null } };
vm.createContext(check);
vm.runInContext(output, check);
for (const module of metadata.modules) if (typeof check[module.functionName] !== 'function') throw Error('Missing entry ' + module.functionName);
fs.writeFileSync(path.join(root, 'widgets/fw-trace.js'), output);
